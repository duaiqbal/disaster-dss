class Tr {
  static String t(String key) {
    final lang = LanguageService.instance.current;
    final dict = _translations[lang] ?? _translations[AppLanguage.english]!;
    return dict[key] ?? _translations[AppLanguage.english]![key] ?? key;
  }

  static String riskLevel(String level) {
    final lower = level.toLowerCase();
    if (lower.contains('high')) return t('risk_high');
    if (lower.contains('moderat')) return t('risk_moderate');
    if (lower.contains('low')) return t('risk_low');
    return level;
  }

  static String weatherCondition(String condition) {
    final lower = condition.toLowerCase();
    if (lower.contains('heavy rain')) return LanguageService.instance.isUrdu ? 'شدید بارش' : condition;
    if (lower.contains('rain')) return LanguageService.instance.isUrdu ? 'بارش' : condition;
    if (lower.contains('cloud')) return LanguageService.instance.isUrdu ? 'ابر آلود' : condition;
    if (lower.contains('sunny') || lower.contains('clear')) return LanguageService.instance.isUrdu ? 'صاف موسم' : condition;
    return condition;
  }

  static String dayName(String day) {
    final lower = day.toLowerCase().trim();
    if (lower.startsWith('mon')) return t('day_mon');
    if (lower.startsWith('tue')) return t('day_tue');
    if (lower.startsWith('wed')) return t('day_wed');
    if (lower.startsWith('thu')) return t('day_thu');
    if (lower.startsWith('fri')) return t('day_fri');
    if (lower.startsWith('sat')) return t('day_sat');
    if (lower.startsWith('sun')) return t('day_sun');
    return day;
  }

